"""Generate paper/numbers.tex (LaTeX macros) and paper/figures/*.pdf from results/*.json.

Every result value taken from results/*.json is a macro defined here, so regenerating keeps the
manuscript in step with the analysis. Values from checks whose output is not in results/ (the
injection pull width; the post-hoc A/B covariance audit, written outside the repository) are
typed in main.tex next to a "% typed value" comment and need manual review when those checks
are rerun.

Usage:
    python paper/make_inputs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
RES = REPO / "results"
OUT = REPO / "paper"
FIG = OUT / "figures"
DET = ["100A", "100B", "143A", "143B", "217A", "217B", "353A", "353B"]

PDF_META = {"CreationDate": None}          # no timestamp: identical results give identical figures
plt.rcParams.update({"font.size": 8, "axes.linewidth": 0.6, "figure.dpi": 150, "savefig.bbox": "tight",
                     "font.family": "serif", "mathtext.fontset": "dejavuserif"})


def load(name):
    p = RES / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def f(x, d=2):
    return f"{x:.{d}f}"


def main() -> int:
    FIG.mkdir(parents=True, exist_ok=True)
    rep, pers, sp, spv, spl = load("reproduction.json"), load("persistence.json"), load("spatial.json"), load("spatial_validation.json"), load("spatial_leakage.json")
    npe, npev, pv = load("npe.json"), load("npe_validation.json"), load("persistence_validation.json")
    m0, m30 = rep["per_mask"]["0"], rep["per_mask"]["30"]
    cd = m0["chi2_diff"]
    pulls = sorted(cd["pulls"].items(), key=lambda kv: -abs(kv[1]))
    tex = ["% generated by paper/make_inputs.py from results/*.json; do not edit\n"]
    add = lambda n, v: tex.append(macro(n, v))
    # reproduction
    add("fskyA", f(rep["masks"]["fsky"]["0"])); add("fskyB", f(rep["masks"]["fsky"]["30"]))
    add("netChiA", f(m0["network"]["chi2"], 1)); add("netPteA", f(m0["network"]["pte"]))
    add("netChiB", f(m30["network"]["chi2"], 1)); add("netPteB", f(m30["network"]["pte"]))
    add("chiDiff", f(cd["chi2"])); add("pteDiff", f(cd["pte"])); add("nBoot", f"{cd['n_sims']:,}".replace(",", "{,}"))
    add("maxPullMap", pulls[0][0]); add("maxPull", f"{pulls[0][1]:+.2f}")
    add("pearsonR", f(m0["pearson_r_pairs"], 3))
    add("betaMK", f(m0["mk"]["beta_deg"])); add("sigBetaMK", f(m0["mk"]["sigma_beta_deg"]))
    add("betaProf", f(m0["mk"]["beta_profile"]["quadratic_beta_deg"])); add("sigBetaProf", f(m0["mk"]["beta_profile"]["quadratic_sigma_deg"]))
    v = m0["mk"]["beta_by_dust_eb_amplitudes"]
    add("betaNoDust", f(v["0"]["beta_deg"])); add("sigBetaNoDust", f(v["0"]["sigma_deg"]))
    add("betaOneA", f(v["1"]["beta_deg"])); add("sigBetaOneA", f(v["1"]["sigma_deg"]))
    add("betaAncA", f(m0["anchored_beta_deg"])); add("betaAncB", f(m30["anchored_beta_deg"])); add("sigBetaAnc", f(m0["anchored_sigma_deg"]))
    d = rep["dust_ee_over_bb_l_lt_300"]
    for q in ("143", "217", "353"):
        add(f"dustRatio{['A', 'B', 'C'][('143', '217', '353').index(q)]}", f(d[q]["lcdm_subtracted"]))
    # spatial
    if sp and spv:
        for sc, k in (("base12", "Tw"), ("lat8", "Ei")):
            o, vv = sp["schemes"][sc], spv["schemes"][sc]
            add(f"spChi{k}", f(o["chi2_spatial"], 1)); add(f"spDof{k}", str(o["dof_spatial"])); add(f"spPte{k}", f(o["pte_spatial"]))
            add(f"clChi{k}", f(o["chi2_closure"], 1)); add(f"clDof{k}", str(o["dof_closure"])); add(f"clPte{k}", f(o["pte_closure"]))
            add(f"abChi{k}", f(o["chi2_ab"], 1)); add(f"abDof{k}", str(o["dof_ab"])); add(f"abPte{k}", f(o["pte_ab"], 3))
            add(f"trChi{k}", f(o["tracer_delta_chi2"], 1)); add(f"trPte{k}", f(o["tracer_pte"]))
            add(f"nullSp{k}", f(vv["null_mean"]["spatial"], 1)); add(f"nullCl{k}", f(vv["null_mean"]["closure"], 1)); add(f"nullAb{k}", f(vv["null_mean"]["ab"], 1))
            pw = {(p["amp_deg"]): p["detection_rate"] for p in vv["power"]["dust_like"]}
            pi = {(p["amp_deg"]): p["detection_rate"] for p in vv["power"]["instrument_like"]}
            add(f"powDust{k}", str(round(100 * pw[0.2]))); add(f"powInst{k}", str(round(100 * pi[0.1])))
        add("nNull", str(spv["schemes"]["base12"]["n_null"]))
        add("abBonf", f(min(1.0, 8 * sp["schemes"]["lat8"]["pte_ab"])))
    if spl:
        add("leakMean", f"{spl['mean_corr_offdiag']:+.3f}"); add("leakMax", f(spl["max_abs_corr_offdiag"], 3)); add("leakFloor", f(spl["sd_expected_noise"]))
    # persistence
    if pers:
        for p, k in (("NGP", "N"), ("SGP", "S"), ("ColdSpot", "C")):
            n0 = pers["stats"][p]["n0"]
            add(f"nz{k}", f"{n0['z']:+.2f}"); add(f"np{k}", f(n0["p_two_sided"], 3)); add(f"nh{k}", f(n0["p_holm"]))
        add("nPers", f"{pers['n_sims']:,}".replace(",", "{,}")); add("nComp", str(pers["n_comparisons"]))
        add("asymZ", f"{pers['ngp_minus_sgp_mean_life0']['z']:+.2f}")
    if pv:
        for null, k in (("gaussian", "G"), ("noise_aniso", "A"), ("phase", "P")):
            for p, kk in (("NGP", "N"), ("SGP", "S"), ("ColdSpot", "C")):
                o = pv["nulls"][null][p]["n0"]
                add(f"pv{k}{kk}z", f"{o['z']:+.2f}"); add(f"pv{k}{kk}h", f(o["p_holm"]))
        add("nPV", f"{pv['n_sims']:,}".replace(",", "{,}"))
    # NPE
    if npev:
        for mdl, k in (("full", "F"), ("M0", "Z"), ("M1", "O"), ("M2", "T"), ("M3", "H")):
            r = npev["models"][mdl]
            add(f"cov{k}", f(r["coverage68"][0])); add(f"covn{k}", f(r["coverage95"][0])); add(f"bsd{k}", f(r["beta_sd_median"], 2))
            if "mk_no_dust_eb" in r:
                add(f"mkBias{k}", f"{r['mk_no_dust_eb']['beta_bias_mean']:+.3f}"); add(f"mkCov{k}", f(r["mk_no_dust_eb"]["coverage68"]))
    if npev:
        for mdl, k in (("full", "F"), ("M0", "Z"), ("M1", "O"), ("M2", "T"), ("M3", "H")):
            dp = npev["models"][mdl]["beta_minus_psi0"]
            add(f"dcov{k}", f(dp["coverage68"])); add(f"dsd{k}", f(dp["sd_median"]))
        add("mkSlopeO", f"{npev['models']['M1']['mk_no_dust_eb']['beta_err_vs_common_slope']:+.2f}")
        add("mkSlopeZ", f"{npev['models']['M0']['mk_no_dust_eb']['beta_err_vs_common_slope']:+.2f}")
        add("nTest", f"{npev['n_test']:,}".replace(",", "{,}"))
        if "psi_prior_reweighted" in npev:
            add("rwKH", f(npev["psi_prior_reweighted"]["psiN0p5"]["interval_scale"]["k68"]))
        add("dcovnF", f(npev["models"]["full"]["beta_minus_psi0"]["coverage95"]))
        for mdl, k in (("psiN0p5", "H"), ("psiN1", "O")):
            r = npev.get("psi_prior_reweighted", {}).get(mdl)
            if r:
                add(f"rwCov{k}", f(r["coverage68"])); add(f"rwCovn{k}", f(r["coverage95"])); add(f"rwHw{k}", f(r["beta_halfwidth68_median"]))
    fis = load("npe_fisher.json")
    if fis:
        add("fisNoDust", f(fis["sigma_beta_deg"]["no_dust_eb"], 3))
        # with psi free the Fisher matrix is singular in beta (exact degeneracy); report it as such
        full = fis["sigma_beta_deg"]["full"]
        add("fisFull", r"\infty" if full is None or full > 100 else f(full))
        if fis.get("full_min_relative_eigenvalue") is not None:
            e = int(np.floor(np.log10(fis["full_min_relative_eigenvalue"])))
            add("fisEig", rf"\sim10^{{{e}}}")
        if fis["corr_beta_psi0"] is not None:
            add("fisCorr", f(fis["corr_beta_psi0"]))
    if npe:
        b = npe["posterior"]["beta"]
        add("npeBeta", f(b["median"])); add("npeUp", f(b["hi68"] - b["median"])); add("npeLo", f(b["median"] - b["lo68"]))
        add("npeLoN", f(b["lo95"])); add("npeHiN", f(b["hi95"]))
        cal = npe.get("calibrated", {})          # intervals widened by the validated scale max(1, k)
        d = cal.get("beta_minus_psi0", npe["beta_minus_psi0"])
        add("dOffset", f(0.30 - d["median"], 1))  # published no-dust-EB PR4 value 0.30 deg (Diego-Palazuelos et al. 2022)
        add("dBeta", f"{d['median']:+.2f}"); add("dUp", f(d["hi68"] - d["median"])); add("dLo", f(d["median"] - d["lo68"]))
        for w, k in (("0.5", "H"), ("1.0", "O"), ("2.0", "T")):
            g = cal.get("beta_given_psi_prior", npe["beta_given_psi_prior"])[f"psi0~N(0,{w})"]
            add(f"bPsi{k}", f"{g['median']:+.2f}"); add(f"bPsi{k}Up", f(g["hi68"] - g["median"])); add(f"bPsi{k}Lo", f(g["median"] - g["lo68"]))
    (OUT / "numbers.tex").write_text("".join(tex), encoding="utf-8")

    # Figure 1: per-map pattern, network vs MK
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    g = DET.index("143A")
    na, ns = np.array(m0["network"]["alpha_deg"]), np.array(m0["network"]["sigma_deg"])
    ma = np.array(m0["mk"]["alpha_deg"]) - m0["mk"]["alpha_deg"][g]
    ms = np.array(m0["mk"].get("sigma_rel_gauge_deg", m0["mk"]["sigma_alpha_deg"]))
    x = np.arange(8)
    ax.errorbar(x - 0.12, na, ns, fmt="o", ms=3, lw=0.8, color="k", label="network (birefringence-blind)")
    ax.errorbar(x + 0.12, ma, ms, fmt="s", ms=3, lw=0.8, color="C3", label="MK likelihood")
    ax.axhline(0, color="0.6", lw=0.5)
    ax.set_xticks(x, DET, rotation=45)
    ax.set_ylabel(r"$\alpha_i - \alpha_{143A}$ [deg]")
    ax.legend(frameon=False, fontsize=6.5)
    fig.savefig(FIG / "fig_pattern.pdf", metadata=PDF_META)
    plt.close(fig)

    # Figure 2: spatial contributions and drift grid
    if sp:
        s = sp["schemes"]["base12"]
        fig, axs = plt.subplots(1, 2, figsize=(7.0, 2.3), gridspec_kw={"width_ratios": [1, 1.2]})
        c = np.array(s["chi2_spatial_region"])
        dust = np.array(s["dust_tracer"])
        col = plt.cm.Reds((np.log(dust) - np.log(dust).min()) / np.ptp(np.log(dust)) * 0.8 + 0.15)
        axs[0].bar(range(len(c)), c, color=col)
        axs[0].axhline(7, ls="--", lw=0.6, color="C0")
        axs[0].set_xticks(range(len(c)), s["labels"], rotation=90, fontsize=6)
        axs[0].set_ylabel(r"$\chi^2_{\rm spatial}$ contribution")
        z = np.array(s["gamma_deg"]) / np.where(np.array(s["gamma_sigma_deg"]) > 0, np.array(s["gamma_sigma_deg"]), np.inf)
        im = axs[1].imshow(z.T, cmap="RdBu_r", vmin=-3, vmax=3, aspect="auto")
        axs[1].set_yticks(range(8), DET, fontsize=6)
        axs[1].set_xticks(range(len(c)), s["labels"], rotation=90, fontsize=6)
        fig.colorbar(im, ax=axs[1], label=r"$\gamma_i(r)/\sigma$")
        fig.savefig(FIG / "fig_spatial.pdf", metadata=PDF_META)
        plt.close(fig)

    # Figure 3: SBC coverage per dust model (if available)
    if npev:
        fig, ax = plt.subplots(figsize=(3.4, 2.1))
        mods = ["full", "M0", "M1", "M2", "M3"]
        c68 = [npev["models"][m]["coverage68"][0] for m in mods]
        c95 = [npev["models"][m]["coverage95"][0] for m in mods]
        xx = np.arange(len(mods))
        ax.plot(xx, c68, "o", color="k", ms=3, label="68% intervals")
        ax.plot(xx, c95, "s", color="C3", ms=3, label="95% intervals")
        for lvl in (0.68, 0.95):
            ax.axhline(lvl, color="0.6", lw=0.5, ls="--")
        mk = [npev["models"][m].get("mk_no_dust_eb", {}).get("coverage68", np.nan) for m in mods]
        ax.plot(xx, mk, "x", color="C0", label="MK, no dust EB (68%)")
        ax.set_xticks(xx, mods)
        ax.set_ylabel(r"coverage of $\beta$")
        ax.set_ylim(0, 1.05)
        ax.legend(frameon=False, fontsize=6)
        fig.savefig(FIG / "fig_coverage.pdf", metadata=PDF_META)
        plt.close(fig)
    print("wrote", OUT / "numbers.tex", "and figures:", sorted(p.name for p in FIG.glob("*.pdf")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
